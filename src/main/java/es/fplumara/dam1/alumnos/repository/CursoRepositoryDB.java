    @Override
    public void deletePorNombre(String texto) {
        String sql = "DELETE from cursos where nombre like %?%";

        try (Connection c = getConnection(); PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setString(1, texto);

            ps.executeUpdate();

        } catch (SQLException e) {
            throw new RuntimeException("Error eliminando cursos", e);
        }
    }

    @Override
    public List<Curso> listarPorEstado(boolean estado) {

        String sql = "select * from cursos where activo = ?";

        try (Connection c = getConnection(); PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setBoolean(1, estado);

            ResultSet rs = ps.executeQuery();

            List<Curso> cursos = new ArrayList<>();

            while (rs.next()){
                Curso curso = new Curso();
                curso.setId(rs.getInt("id"));
                curso.setNombre(rs.getString("nombre"));
                curso.setEstado(rs.getBoolean("activo"));

                curso.add(curso);
            }

            return cursos;
        } catch (SQLException e) {
            throw new RuntimeException("Error listado por estado", e);
        }

    }

