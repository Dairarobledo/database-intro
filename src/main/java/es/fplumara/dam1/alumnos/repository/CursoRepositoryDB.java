    public CursoRepositoryDB(String url, String user, String pass) {
        this.url = url;
        this.user = user;
        this.pass = pass;
    }
    private Connection getConnection() throws SQLException {
        return DriverManager.getConnection(url, user, pass);
    }
    @Override
    public void initSchema() {
        String ddl = """
                CREATE TABLE IF NOT EXISTS cursos (
                  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  activo boolean,
                  nombre varchar(10)
                );
                """;
        try{
            Connection c = getConnection();
            Statement st = c.createStatement();
            st.execute(ddl);
            } catch (SQLException e) {
            throw new RuntimeException("Error inicializado en schemma ", e);
        }
    }

    @Override
    public Optional<Curso> findById(Integer id) {
        if (id == null) {
            return Optional.empty();
        }
        String sql = "SELECT id, estado , nombre  FROM Curso WHERE id = ?";

        try {
            Connection c = getConnection();
            PreparedStatement ps = c.prepareStatement(sql);
            ps.setInt(1, id);
            ResultSet rs = ps.executeQuery();
            if(!rs.next()){
                return Optional.empty();
            }
            return Optional.of(mapClase(rs));
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    @Override
    public List<Curso> findAll() {
        String sql = "SELECT id,activo, nombre FROM cursos ORDER BY id";

        try {
            Connection c = getConnection();
            PreparedStatement ps = c.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();

            List<Curso> curso = new ArrayList<>();
            while (rs.next()) {
                curso.add();
            }
            return curso;

        } catch (SQLException e) {
            throw new RuntimeException("Error listando cursos", e);
        }
    }

